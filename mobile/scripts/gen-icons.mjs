#!/usr/bin/env node
/**
 * Regenerates src/icons/glyphs.ts from the web's Paper sprite
 * (app/components/paper/PaperIcon.tsx), so the phone draws the exact same
 * hand-drawn glyphs and the two can't drift. Run: npm run gen:icons
 *
 * The sprite is a flat string of <symbol id="pp-NAME" viewBox="0 0 24 24">…</symbol>
 * whose children are only path / circle / rect / g, so a small tokenizer is
 * enough. Anything else fails loudly instead of being dropped.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../app/components/paper/PaperIcon.tsx");
const out = resolve(here, "../src/icons/glyphs.ts");

const file = readFileSync(src, "utf8");
const m = file.match(/const SPRITE = ("(?:[^"\\]|\\.)*");/);
if (!m) throw new Error(`SPRITE string not found in ${src}`);
const sprite = JSON.parse(m[1]);

const ATTR = {
  d: "d", fill: "fill", stroke: "stroke", "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap", "stroke-linejoin": "strokeLinejoin",
  "stroke-dasharray": "strokeDasharray", cx: "cx", cy: "cy", r: "r",
  x: "x", y: "y", width: "width", height: "height", rx: "rx",
};
const NUMERIC = new Set(["strokeWidth", "cx", "cy", "r", "x", "y", "width", "height", "rx"]);
const TAGS = new Set(["path", "circle", "rect", "g"]);

function attrs(raw) {
  const o = {};
  for (const [, k, v] of raw.matchAll(/([a-z-]+)="([^"]*)"/g)) {
    const key = ATTR[k];
    if (!key) throw new Error(`unknown attribute ${k}`);
    o[key] = NUMERIC.has(key) ? Number(v) : v;
  }
  return o;
}

/** Parse a symbol's inner markup into [tag, attrs, children?] nodes. */
function parse(markup) {
  const root = [];
  const stack = [root];
  for (const [, close, tag, raw, selfClose] of markup.matchAll(/<(\/?)([a-z]+)([^>]*?)(\/?)>/g)) {
    if (!TAGS.has(tag)) throw new Error(`unsupported element <${tag}>`);
    if (close) { stack.pop(); continue; }
    const node = [tag, attrs(raw)];
    stack[stack.length - 1].push(node);
    if (!selfClose) { node.push([]); stack.push(node[2]); }
  }
  return root;
}

const glyphs = {};
for (const [, id, viewBox, inner] of sprite.matchAll(/<symbol id="pp-([a-z0-9-]+)" viewBox="([^"]+)">(.*?)<\/symbol>/g)) {
  if (viewBox !== "0 0 24 24") throw new Error(`pp-${id}: expected a 24×24 viewBox, got ${viewBox}`);
  glyphs[id] = parse(inner);
}
const names = Object.keys(glyphs).sort();
if (names.length < 50) throw new Error(`only ${names.length} glyphs parsed; the sprite format changed`);

const body = `/* GENERATED by scripts/gen-icons.mjs from app/components/paper/PaperIcon.tsx. Do not edit. */

export type GlyphTag = "path" | "circle" | "rect" | "g";
export type GlyphNode = readonly [GlyphTag, Readonly<Record<string, string | number>>, ReadonlyArray<GlyphNode>?];

export const GLYPH_NAMES = ${JSON.stringify(names)} as const;
export type GlyphName = (typeof GLYPH_NAMES)[number];

export const GLYPHS: Record<GlyphName, ReadonlyArray<GlyphNode>> = ${JSON.stringify(glyphs, null, 0)
  .replace(/\],"/g, '],\n  "')};
`;
writeFileSync(out, body);
console.log(`wrote ${names.length} glyphs → ${out}`);
